import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const OUTPUT = "public/third-party-licenses.txt";
const HEADER = "Third-party software in 5Stack Web";
const PACKAGES = [{ dir: ".", dev: true }];

// Vite bundles devDependencies into the build, so they are walked too. Only
// packages that ship nothing into the build are skipped, and optional
// dependencies are left out because they are platform-specific build binaries.
const TOOLING =
  /^(@types\/|@nuxt\/devtools$|@nuxt\/test-utils$|@vue\/test-utils$|@vitejs\/plugin-vue$|vitest$|vue-tsc$|typescript$|prettier$|autoprefixer$|postcss$|postcss-nesting$|esbuild$)/;

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i;

function resolvePackage(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, "node_modules", name, "package.json");
    if (existsSync(candidate)) {
      return realpathSync(dirname(candidate));
    }
    const parent = dirname(dir);
    if (parent === dir) {
      return null;
    }
    dir = parent;
  }
}

function licenseText(dir, pkg) {
  const files = readdirSync(dir)
    .filter((file) => LICENSE_FILE.test(file))
    .sort();
  if (files.length === 0) {
    const repository = pkg.repository?.url ?? pkg.repository;
    return `License: ${pkg.license ?? `not stated in the package, see ${repository ?? pkg.homepage ?? "its npm page"}`}`;
  }
  return files
    .map((file) => readFileSync(join(dir, file), "utf8").replace(/\r\n?/g, "\n").trim())
    .join("\n\n");
}

const root = process.cwd();
const queue = [];
for (const { dir, dev } of PACKAGES) {
  const packageDir = join(root, dir);
  const pkg = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
  const names = Object.keys(pkg.dependencies ?? {});
  if (dev) {
    names.push(...Object.keys(pkg.devDependencies ?? {}).filter((name) => !TOOLING.test(name)));
  }
  queue.push(...names.map((name) => [name, packageDir]));
}

const seen = new Set();
const byText = new Map();

while (queue.length > 0) {
  const [name, fromDir] = queue.shift();
  const dir = resolvePackage(name, fromDir);
  if (!dir || seen.has(dir)) {
    continue;
  }
  seen.add(dir);

  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const text = licenseText(dir, pkg);
  if (!byText.has(text)) {
    byText.set(text, new Set());
  }
  byText.get(text).add(pkg.name ?? name);

  for (const dependency of Object.keys(pkg.dependencies ?? {})) {
    queue.push([dependency, dir]);
  }
}

const groups = [...byText.entries()]
  .map(([text, names]) => [text, [...names].sort()])
  .sort(([, a], [, b]) => a[0].localeCompare(b[0]));

const sections = groups.map(
  ([text, names]) =>
    `The following npm packages may be included in this product:\n\n${names
      .map((name) => ` - ${name}`)
      .join("\n")}\n\nThese packages each contain the following license:\n\n${text}`,
);

writeFileSync(
  join(root, OUTPUT),
  `${HEADER}\n\nGenerated by scripts/third-party-notices.mjs from the installed node_modules.\n\n-----------\n\n${sections.join("\n\n-----------\n\n")}\n`,
);

console.log(`${seen.size} packages, ${groups.length} license texts -> ${OUTPUT}`);
